//   /System/Library/Frameworks/JavaScriptCore.framework/Versions/Current/Helpers/jsc -m tests/run.mjs
// (or any ES-module JS runtime, e.g. `node tests/run.mjs`)

import { buildIni, parseIni, defaultTrigger, triggerLine, triggerFlags, applyFunctionDefaults, isDefaultTrigger, defaultGlobal } from '../app/js/ini.js';
import { parseTrackFileName, buildFileName, sanitizeLabel } from '../app/js/naming.js';
import { encodeWav16 } from '../app/js/wav.js';
import { crc32 } from '../app/js/zip.js';

const print = globalThis.print || console.log;
let pass = 0, fail = 0;
function eq(actual, expected, name) {
  const a = JSON.stringify(actual), e = JSON.stringify(expected);
  if (a === e) pass++;
  else { fail++; print(`FAIL ${name}\n  expected ${e}\n  actual   ${a}`); }
}

// --- triggers: byte-compatible with the Robertsonics Configurator ---
const d = defaultTrigger(1);
eq(triggerFlags(d), 0x50, 'default flags = retrigger|poly = 80');
eq(isDefaultTrigger(d), true, 'default trigger detected');
eq(triggerLine(d), '#TRIG 01, 80, 0, 0, 1, ,', 'normal trigger line format');
const rnd = { ...applyFunctionDefaults(defaultTrigger(3), 4), low: 33, high: 48 };
eq(triggerLine(rnd), '#TRIG 03, 80, 0, 0, 4, 33, 48', 'random trigger line');
const lvl = { ...defaultTrigger(12), type: 1, retrigger: false, loop: true, output: 2, gain: -6 };
eq(triggerLine(lvl), '#TRIG 12, 97, -6, 2, 1, ,', 'level+loop, output 3, -6 dB');
const up = applyFunctionDefaults(defaultTrigger(16), 12);
eq(triggerLine(up), '#TRIG 16, 0, 0, 0, 12, ,', 'bank up');

// --- full ini round trip ---
const g = { ...defaultGlobal(), outVol: [-6, 0, 3, 0, 0, 0, 0, 0], midiChannel: 10, bend: 5, release: 40, ignoreOff: true, dbnc: 5, imix: 3 };
const triggers = Array.from({ length: 16 }, (_, i) => defaultTrigger(i + 1));
triggers[2] = rnd; triggers[11] = lvl; triggers[15] = up;
const ini = buildIni({ mode: 'mono', global: g, triggers });
const lines = ini.split('\r\n');
eq(lines[0], '#TSUM', 'mono header first');
eq(lines.includes('#VOL1 -6') && lines.includes('#VOL3 3'), true, 'volume lines');
eq(lines.includes('#MCHN 10') && lines.includes('#BEND 5') && lines.includes('#MREL 40') && lines.includes('#MIDI 4'), true, 'midi lines');
eq(lines.includes('#DBNC 5') && lines.includes('#IMIX 3'), true, 'dbnc + imix');
eq(lines.filter(l => l.startsWith('#TRIG')).length, 3, 'only non-default triggers written');
const back = parseIni(ini);
eq(back.mode, 'mono', 'parse mode');
eq(back.global.outVol, g.outVol, 'parse volumes');
eq([back.global.midiChannel, back.global.bend, back.global.release, back.global.ignoreOff, back.global.ignoreVel, back.global.dbnc, back.global.imix], [10, 5, 40, true, false, 5, 3], 'parse midi/global');
eq(back.triggers.map(t => triggerLine(t)), [triggerLine(rnd), triggerLine(lvl), triggerLine(up)], 'parse triggers round-trip');

// A file as written by the official Configurator v2.20
const official = '#TSUS\n#VOL1 -10\r\n#TRIG 01, 80, 0, 0, 1, ,\r\n#TRIG 02, 82, 0, 1, 2, 1, 16\r\n******\r\nThis file was generated by the Robertsonics Configurator v2.20\r\n';
const po = parseIni(official);
eq([po.mode, po.global.outVol[0], po.triggers.length, po.triggers[1].type, po.triggers[1].low, po.triggers[1].high, po.triggers[1].output], ['stereo', -10, 2, 2, 1, 16, 1], 'parse official configurator output');

// --- naming (User Guide examples) ---
eq(parseTrackFileName('1-Music Loop 21.wav').num, 1, 'guide ex 1');
eq(parseTrackFileName('438_Barking Dog.wav').num, 438, 'guide ex 2');
const v = parseTrackFileName('0101_L3 Violin A3.wav');
eq([v.num, v.midi.loop, v.midi.out, v.label], [101, true, 3, 'Violin A3'], 'guide ex 3');
const f = parseTrackFileName('4096_S4 Flute B3.wav');
eq([f.num, f.midi.loop, f.midi.out, f.valid], [4096, false, 4, true], 'guide ex 4');
eq(parseTrackFileName('031_S1~trigger.WAV').midi.out, 1, 'nutella example');
eq(parseTrackFileName('4097_x.wav').valid, false, '4097 invalid');
eq(parseTrackFileName('12345.wav').valid, false, '5 digits invalid');
eq(parseTrackFileName('kick.wav'), null, 'no number');

const naming = { digits: 4, sep: '_', ascii: true, alwaysSuffix: false, maxLen: 64 };
eq(buildFileName({ num: 1, name: 'Kick 808', midi: { loop: false, out: 1 } }, naming, 'stereo'), '0001_Kick 808.wav', 'build plain');
eq(buildFileName({ num: 101, name: 'Violin A3', midi: { loop: true, out: 3 } }, naming, 'mono'), '0101_L3 Violin A3.wav', 'build with suffix');
eq(buildFileName({ num: 7, name: 'S2 bass', midi: { loop: false, out: 1 } }, naming, 'mono'), '0007-S2 bass.wav', 'ambiguous label guarded');
eq(parseTrackFileName(buildFileName({ num: 7, name: 'S2 bass', midi: { loop: false, out: 1 } }, naming, 'mono')).midi, null, 'guarded name parses without suffix');
eq(sanitizeLabel('Bjørk: “Hyperballad” / take 2?'), 'Bjork Hyperballad take 2', 'sanitize');

// --- wav encoder ---
const { bytes, clipped } = encodeWav16([new Float32Array([0, 0.5, -1, 1.5])], { dither: false });
const dv = new DataView(bytes.buffer);
eq(bytes.length, 44 + 8, 'wav size');
eq(String.fromCharCode(...bytes.slice(0, 4)) + String.fromCharCode(...bytes.slice(8, 16)) + String.fromCharCode(...bytes.slice(36, 40)), 'RIFFWAVEfmt data', 'canonical chunk order');
eq([dv.getUint16(22, true), dv.getUint32(24, true), dv.getUint16(34, true), dv.getUint32(40, true)], [1, 44100, 16, 8], 'fmt fields');
eq([dv.getInt16(44, true), dv.getInt16(46, true), dv.getInt16(48, true), dv.getInt16(50, true), clipped], [0, 16384, -32767, 32767, 1], 'samples + clip count');

// --- crc32 known vector ---
const enc = s => Uint8Array.from(s, c => c.charCodeAt(0));
eq(crc32(enc('123456789')).toString(16), 'cbf43926', 'crc32 check value');

print(`${pass} passed, ${fail} failed`);
if (fail && typeof process !== 'undefined') process.exit(1);
