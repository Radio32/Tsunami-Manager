// tsunami.ini reader/writer.
// Line grammar mirrors the Robertsonics Configurator (WTConfig, OutputComponent.cpp):
//   #TSUS | #TSUM                       first line, stereo / mono firmware
//   #TRIG NN, Flags, Gain, Output, Function, Low, High
//   #VOLn dB  #IMIX mask  #MCHN ch  #BEND st  #MREL ms  #MIDI flags  #BAUD rate
//   #DBNC ms  (undocumented debounce, recommended by the Nutella manual)

import { TF, FUNC_BY_CODE } from './constants.js';

const NL = '\r\n';
const RANGE_FUNCS = new Set([2, 3, 4, 5, 6, 7, 14]);
export const funcHasRange = code => RANGE_FUNCS.has(code);

export function defaultTrigger(num) {
  return {
    num, func: 1, type: 0, iface: 0, invert: false,
    retrigger: true, loop: false, poly: true, lock: false,
    gain: 0, output: 0, low: 0, high: 0,
  };
}

// Same per-function defaults the Configurator applies when you change the function box.
export function applyFunctionDefaults(t, code) {
  const n = { ...t, func: code, gain: 0, output: 0, lock: false, loop: false };
  const edgeLike = n.type !== 1;
  switch (code) {
    case 1: Object.assign(n, { low: 0, high: 0, poly: true, retrigger: edgeLike }); break;
    case 2: case 3: case 4:
      Object.assign(n, { low: t.low || 1, high: t.high || 16, poly: true, type: 0, retrigger: true }); break;
    case 5: case 6: case 7:
      Object.assign(n, { low: t.low || 1, high: t.high || 16, poly: false, retrigger: false }); break;
    case 14:
      Object.assign(n, { low: t.low || 1, high: t.high || 8, poly: true, retrigger: edgeLike }); break;
    default:
      Object.assign(n, { low: 0, high: 0, poly: false, retrigger: false, type: 0 }); break;
  }
  return n;
}

export function triggerFlags(t) {
  let f = t.type & TF.TYPE;
  if (t.iface) f |= TF.INTERFACE;
  if (t.invert) f |= TF.INVERT;
  if (t.retrigger) f |= TF.RETRIGGER;
  if (t.loop) f |= TF.LOOP;
  if (t.poly) f |= TF.POLY;
  if (t.lock) f |= TF.LOCK;
  return f;
}

export function triggerFromFields(num, flags, gain, output, func, low, high) {
  return {
    num,
    func: FUNC_BY_CODE[func] ? func : 1,
    type: Math.min(2, flags & TF.TYPE),
    iface: flags & TF.INTERFACE ? 1 : 0,
    invert: !!(flags & TF.INVERT),
    retrigger: !!(flags & TF.RETRIGGER),
    loop: !!(flags & TF.LOOP),
    poly: !!(flags & TF.POLY),
    lock: !!(flags & TF.LOCK),
    gain: gain | 0,
    output: output | 0,
    low: funcHasRange(func) ? low | 0 : 0,
    high: funcHasRange(func) ? high | 0 : 0,
  };
}

export function isDefaultTrigger(t) {
  return t.func === 1 && triggerFlags(t) === (TF.RETRIGGER | TF.POLY) && t.gain === 0 && t.output === 0;
}

export function triggerLine(t) {
  let s = `#TRIG ${String(t.num).padStart(2, '0')}, ${triggerFlags(t)}, ${t.gain}, ${t.output}, ${t.func}, `;
  s += funcHasRange(t.func) ? `${t.low}, ${t.high}` : ',';
  return s;
}

export function defaultGlobal() {
  return {
    baud: 57600,
    outVol: [0, 0, 0, 0, 0, 0, 0, 0],
    imix: 0,
    midiChannel: 0,     // 0 = Omni, 1..16
    bend: 2,            // semitones 1..5
    release: 0,         // ms, 0..127
    ignoreVel: false,
    ignoreOff: false,
    dbnc: null,         // ms, null = firmware default (~50 ms)
    extraLines: '',
  };
}

export function buildIni({ mode, global: g, triggers }, { generator = 'Nutella Tsunami Manager' } = {}) {
  const out = [mode === 'mono' ? '#TSUM' : '#TSUS'];
  if (g.baud && g.baud !== 57600) out.push(`#BAUD ${g.baud}`);
  const outputs = mode === 'mono' ? 8 : 4;
  for (let i = 0; i < outputs; i++) {
    const v = Math.round(g.outVol[i] || 0);
    if (v !== 0) out.push(`#VOL${i + 1} ${v}`);
  }
  if (g.imix > 0) out.push(`#IMIX ${g.imix & 0x0f}`);
  if (g.midiChannel > 0) out.push(`#MCHN ${g.midiChannel}`);
  if (g.bend && g.bend !== 2) out.push(`#BEND ${g.bend}`);
  if (g.release > 0) out.push(`#MREL ${Math.round(g.release)}`);
  const mf = (g.ignoreVel ? 0x02 : 0) | (g.ignoreOff ? 0x04 : 0);
  if (mf) out.push(`#MIDI ${mf}`);
  if (g.dbnc != null && g.dbnc !== '') out.push(`#DBNC ${Math.round(g.dbnc)}`);
  for (const line of (g.extraLines || '').split(/\r?\n/)) {
    const l = line.trim();
    if (l) out.push(l);
  }
  for (const t of [...triggers].sort((a, b) => a.num - b.num)) {
    if (!isDefaultTrigger(t)) out.push(triggerLine(t));
  }
  out.push(
    '******************************************************************',
    `This file was generated by ${generator}`,
    `for use with the Tsunami ${mode === 'mono' ? 'Mono' : 'Stereo'} firmware. It is only required if`,
    'you wish to over-ride default settings. You may add your own',
    'comments below this line -->',
  );
  return out.join(NL) + NL;
}

const KNOWN = new Set(['#TSUS', '#TSUM', '#TRIG', '#BAUD', '#VOL1', '#VOL2', '#VOL3', '#VOL4',
  '#VOL5', '#VOL6', '#VOL7', '#VOL8', '#IMIX', '#MCHN', '#BEND', '#MREL', '#MIDI', '#DBNC']);

export function parseIni(text) {
  const g = defaultGlobal();
  const triggers = [];
  const extra = [];
  const warnings = [];
  let mode = null;
  const lines = text.replace(/^﻿/, '').split(/\r?\n/);
  const first = lines.find(l => l.trim());
  if (first?.trim().startsWith('#TSUS')) mode = 'stereo';
  else if (first?.trim().startsWith('#TSUM')) mode = 'mono';
  else warnings.push('First line is not #TSUS or #TSUM — this may be a WAV Trigger file.');

  for (const raw of lines) {
    const line = raw.trim();
    if (!line.startsWith('#')) continue;
    const key = line.slice(0, 5).toUpperCase();
    const val = parseInt(line.slice(5).trim(), 10);
    if (!KNOWN.has(key)) { extra.push(line); continue; }
    switch (key) {
      case '#BAUD': if (val) g.baud = val; break;
      case '#IMIX': g.imix = (val || 0) & 0x0f; break;
      case '#MCHN': g.midiChannel = val || 0; break;
      case '#BEND': g.bend = val || 2; break;
      case '#MREL': g.release = val || 0; break;
      case '#MIDI': g.ignoreVel = !!(val & 0x02); g.ignoreOff = !!(val & 0x04); break;
      case '#DBNC': g.dbnc = isNaN(val) ? null : val; break;
      case '#TRIG': {
        const tok = line.slice(5).split(',').map(s => s.trim());
        const n = parseInt(tok[0], 10);
        if (!(n >= 1 && n <= 16)) { warnings.push(`Ignored trigger line with bad number: ${line}`); break; }
        if (tok.length >= 9 && tok[8] !== '') {
          warnings.push(`Trigger ${n} looks like WAV Trigger syntax and was skipped.`);
          break;
        }
        const num = i => parseInt(tok[i], 10) || 0;
        triggers.push(triggerFromFields(n, num(1), num(2), num(3), num(4) || 1, num(5), num(6)));
        break;
      }
      default:
        if (key.startsWith('#VOL')) g.outVol[parseInt(key[4], 10) - 1] = val || 0;
    }
  }
  g.extraLines = extra.filter(l => !l.startsWith('#TSU')).join('\n');
  return { mode, global: g, triggers, warnings };
}
